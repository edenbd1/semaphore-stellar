// Generate real Semaphore v4 proofs at several tree depths (1..4), each re-verified with
// snarkjs against that depth's ceremony vkey (ground truth), and emit them Soroban-encoded.
// Proves the verifier / library are depth-general (per-depth vkey), not depth-2-only.
import { Identity } from "@semaphore-protocol/identity"
import { Group } from "@semaphore-protocol/group"
import { generateProof, unpackGroth16Proof } from "@semaphore-protocol/proof"
import * as snarkjs from "snarkjs"
import { keccak256, toBeHex } from "ethers"
import { readFileSync, writeFileSync } from "fs"
import { fileURLToPath } from "url"
import { dirname, resolve } from "path"

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const hash = (m) => (BigInt(keccak256(toBeHex(m, 32))) >> 8n).toString()
const be32 = (d) => BigInt(d).toString(16).padStart(64, "0")
const arr = (hex) => "[" + hex.match(/../g).map((x) => "0x" + x).join(", ") + "]"
const G1 = (p) => arr(be32(p[0]) + be32(p[1]))
const G2 = (p) => arr(be32(p[0][1]) + be32(p[0][0]) + be32(p[1][1]) + be32(p[1][0]))
const g1v = (v) => G1([v[0], v[1]])

// (depth, group size) — LeanIMT depth = ceil(log2(size)), min 1.
const CASES = [[1, 2], [2, 3], [3, 5], [4, 9]]
const L = ["// AUTO-GENERATED by tools/gen-multidepth-fixtures.mjs — real proofs at depths 1..4.", ""]

for (const [depth, size] of CASES) {
    const ids = Array.from({ length: size }, () => new Identity())
    const group = new Group(ids.map((i) => i.commitment))
    const proof = await generateProof(ids[0], group, `msg-d${depth}`, `scope-d${depth}`)
    if (proof.merkleTreeDepth !== depth) throw new Error(`depth ${size}->${proof.merkleTreeDepth}, want ${depth}`)
    const u = unpackGroth16Proof(proof.points)
    const pub = [proof.merkleTreeRoot.toString(), proof.nullifier.toString(), hash(proof.message), hash(proof.scope)]
    const vkey = JSON.parse(readFileSync(resolve(root, `fixtures/vkey-depth${depth}.json`), "utf8"))
    if (!(await snarkjs.groth16.verify(vkey, pub, u))) throw new Error(`ground-truth verify failed at depth ${depth}`)

    const P = `D${depth}`
    L.push(`// depth ${depth} (${size} members)`)
    pub.forEach((s, i) => L.push(`pub const ${P}_PUB_${i}: [u8; 32] = ${arr(be32(s))};`))
    L.push(`pub const ${P}_A: [u8; 64] = ${g1v(u.pi_a)};`)
    L.push(`pub const ${P}_B: [u8; 128] = ${G2(u.pi_b)};`)
    L.push(`pub const ${P}_C: [u8; 64] = ${g1v(u.pi_c)};`)
    L.push(`pub const ${P}_VK_ALPHA: [u8; 64] = ${G1(vkey.vk_alpha_1)};`)
    L.push(`pub const ${P}_VK_BETA: [u8; 128] = ${G2(vkey.vk_beta_2)};`)
    L.push(`pub const ${P}_VK_GAMMA: [u8; 128] = ${G2(vkey.vk_gamma_2)};`)
    L.push(`pub const ${P}_VK_DELTA: [u8; 128] = ${G2(vkey.vk_delta_2)};`)
    vkey.IC.forEach((p, i) => L.push(`pub const ${P}_VK_IC_${i}: [u8; 64] = ${G1(p)};`))
    L.push("")
    console.log(`depth ${depth} (${size} members): ground-truth verified`)
}
writeFileSync(resolve(root, "contracts/verifier/src/fixture_multidepth.rs"), L.join("\n"))
console.log("wrote contracts/verifier/src/fixture_multidepth.rs")
