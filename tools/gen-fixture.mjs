// Reproduce the ground-truth test fixture end to end:
//  1. generate a real Semaphore v4 proof (depth 2) with the Ethereum ceremony artifacts,
//  2. replicate verifyProof() EXACTLY against the depth-2 ceremony vkey (ground truth),
//  3. emit the proof + vkey + public signals as Rust byte constants in Soroban's BN254
//     encoding, for ../contracts/verifier/src/fixture.rs.
//
// Run from this directory:  npm install && node gen-fixture.mjs
import { Identity } from "@semaphore-protocol/identity"
import { Group } from "@semaphore-protocol/group"
import { generateProof, unpackGroth16Proof, verifyProof } from "@semaphore-protocol/proof"
import * as snarkjs from "snarkjs"
import { keccak256, toBeHex } from "ethers"
import { readFileSync, writeFileSync } from "fs"
import { fileURLToPath } from "url"
import { dirname, resolve } from "path"

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, "..")
const VKEY_VERSION = "4.13.0" // must match the artifact version generateProof downloads
const DEPTH = 2

// Semaphore's hash(): keccak256 of the 32-byte value, shifted right by 8 to fit the field.
const hash = (m) => (BigInt(keccak256(toBeHex(m, 32))) >> 8n).toString()

// Fetch the depth-2 ceremony verification key (same version as the proving key).
const vkeyUrl = `https://snark-artifacts.pse.dev/semaphore/${VKEY_VERSION}/semaphore-${DEPTH}.json`
const vkey = await (await fetch(vkeyUrl)).json()
writeFileSync(resolve(root, "fixtures/vkey-depth2.json"), JSON.stringify(vkey, null, 2))

const a = new Identity(), b = new Identity(), c = new Identity()
const group = new Group([a.commitment, b.commitment, c.commitment])
const proof = await generateProof(a, group, "hello-stellar", "stellar-scope-1")
if (proof.merkleTreeDepth !== DEPTH) throw new Error(`unexpected depth ${proof.merkleTreeDepth}`)
if (!(await verifyProof(proof))) throw new Error("lib verifyProof failed")

const u = unpackGroth16Proof(proof.points)
const publicSignals = [
    proof.merkleTreeRoot.toString(),
    proof.nullifier.toString(),
    hash(proof.message),
    hash(proof.scope),
]
if (!(await snarkjs.groth16.verify(vkey, publicSignals, u))) throw new Error("ground-truth verify failed")

const out = {
    treeDepth: proof.merkleTreeDepth,
    publicSignals,
    proof: {
        A: [u.pi_a[0].toString(), u.pi_a[1].toString()],
        B: [[u.pi_b[0][0].toString(), u.pi_b[0][1].toString()], [u.pi_b[1][0].toString(), u.pi_b[1][1].toString()]],
        C: [u.pi_c[0].toString(), u.pi_c[1].toString()],
    },
    vkey: {
        alpha: [vkey.vk_alpha_1[0], vkey.vk_alpha_1[1]],
        beta: [[vkey.vk_beta_2[0][0], vkey.vk_beta_2[0][1]], [vkey.vk_beta_2[1][0], vkey.vk_beta_2[1][1]]],
        gamma: [[vkey.vk_gamma_2[0][0], vkey.vk_gamma_2[0][1]], [vkey.vk_gamma_2[1][0], vkey.vk_gamma_2[1][1]]],
        delta: [[vkey.vk_delta_2[0][0], vkey.vk_delta_2[0][1]], [vkey.vk_delta_2[1][0], vkey.vk_delta_2[1][1]]],
        IC: vkey.IC.map((p) => [p[0], p[1]]),
    },
}
writeFileSync(resolve(root, "fixtures/proof-depth2.json"), JSON.stringify(out, null, 2))

// --- emit Rust fixture in Soroban BN254 encoding ---
const be32 = (dec) => BigInt(dec).toString(16).padStart(64, "0")
const toArr = (hex) => "[" + hex.match(/../g).map((x) => "0x" + x).join(", ") + "]"
const G1 = (p) => toArr(be32(p[0]) + be32(p[1]))                                             // X || Y
const G2 = (p) => toArr(be32(p[0][1]) + be32(p[0][0]) + be32(p[1][1]) + be32(p[1][0]))       // Xc1 Xc0 Yc1 Yc0
const L = ["// AUTO-GENERATED by tools/gen-fixture.mjs — do not edit by hand.",
    "// A real Semaphore v4 (depth 2) proof + ceremony vkey, encoded for Soroban BN254.", ""]
L.push("// Public signals: [merkleTreeRoot, nullifier, hash(message), hash(scope)]")
out.publicSignals.forEach((s, i) => L.push(`pub const PUB_${i}: [u8; 32] = ${toArr(be32(s))};`))
L.push("", "// Proof points",
    `pub const PROOF_A: [u8; 64] = ${G1(out.proof.A)};`,
    `pub const PROOF_B: [u8; 128] = ${G2(out.proof.B)};`,
    `pub const PROOF_C: [u8; 64] = ${G1(out.proof.C)};`,
    "", "// Verification key",
    `pub const VK_ALPHA: [u8; 64] = ${G1(out.vkey.alpha)};`,
    `pub const VK_BETA: [u8; 128] = ${G2(out.vkey.beta)};`,
    `pub const VK_GAMMA: [u8; 128] = ${G2(out.vkey.gamma)};`,
    `pub const VK_DELTA: [u8; 128] = ${G2(out.vkey.delta)};`,
    "", "// IC: 5 points (nPublic + 1)")
out.vkey.IC.forEach((p, i) => L.push(`pub const VK_IC_${i}: [u8; 64] = ${G1(p)};`))
L.push("")
writeFileSync(resolve(root, "contracts/verifier/src/fixture.rs"), L.join("\n"))
console.log("OK: ground-truth verified; wrote fixtures/*.json and contracts/verifier/src/fixture.rs")
