// Emit contracts/semaphore/src/fixture.rs from the existing ground-truth fixtures/proof-depth2.json
// (public signals + proof + depth-2 vkey), encoded for Soroban BN254. No proving needed.
import { readFileSync, writeFileSync } from "fs"
import { fileURLToPath } from "url"
import { dirname, resolve } from "path"
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const f = JSON.parse(readFileSync(resolve(root, "fixtures/proof-depth2.json"), "utf8"))

const be32 = (d) => BigInt(d).toString(16).padStart(64, "0")
const arr = (hex) => "[" + hex.match(/../g).map((x) => "0x" + x).join(", ") + "]"
const G1 = (p) => arr(be32(p[0]) + be32(p[1]))
const G2 = (p) => arr(be32(p[0][1]) + be32(p[0][0]) + be32(p[1][1]) + be32(p[1][0]))

const [root_, nullifier, message, scope] = f.publicSignals
const L = ["// AUTO-GENERATED by tools/gen-semaphore-fixture.mjs — do not edit by hand.",
    "// Real Semaphore v4 depth-2 proof + public signals + ceremony vkey, Soroban-encoded.", "",
    "pub const DEPTH: u32 = 2;",
    `pub const ROOT: [u8; 32] = ${arr(be32(root_))};`,
    `pub const NULLIFIER: [u8; 32] = ${arr(be32(nullifier))};`,
    `pub const MESSAGE: [u8; 32] = ${arr(be32(message))};`,
    `pub const SCOPE: [u8; 32] = ${arr(be32(scope))};`,
    "", "// Proof points",
    `pub const PROOF_A: [u8; 64] = ${G1(f.proof.A)};`,
    `pub const PROOF_B: [u8; 128] = ${G2(f.proof.B)};`,
    `pub const PROOF_C: [u8; 64] = ${G1(f.proof.C)};`,
    "", "// Verification key (depth 2)",
    `pub const VK_ALPHA: [u8; 64] = ${G1(f.vkey.alpha)};`,
    `pub const VK_BETA: [u8; 128] = ${G2(f.vkey.beta)};`,
    `pub const VK_GAMMA: [u8; 128] = ${G2(f.vkey.gamma)};`,
    `pub const VK_DELTA: [u8; 128] = ${G2(f.vkey.delta)};`,
    ""]
f.vkey.IC.forEach((p, i) => L.push(`pub const VK_IC_${i}: [u8; 64] = ${G1(p)};`))
L.push("")
writeFileSync(resolve(root, "contracts/semaphore/src/fixture.rs"), L.join("\n"))
console.log("wrote contracts/semaphore/src/fixture.rs")
